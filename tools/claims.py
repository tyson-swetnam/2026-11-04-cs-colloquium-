"""Validate every slides/*/claims.yaml and build the CLAIMS.md register.

    python tools/claims.py validate   # schema + evidence-path checks (CI runs this)
    python tools/claims.py index      # rewrite CLAIMS.md
    python tools/claims.py check      # validate, and fail if CLAIMS.md is stale
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SLIDES_DIR = ROOT / "slides"
REGISTER = ROOT / "CLAIMS.md"

KINDS = {
    "quantitative",  # a number that code and data can reproduce
    "factual",  # a checkable fact (dates, names, award numbers, identifiers)
    "attribution",  # a quote, figure or number credited to a named source
    "technical",  # a statement about how a system behaves; checked by running it
    "qualitative",  # framing or opinion; record the reasoning, not a verdict
    "placeholder",  # bracketed text on the slide that still needs writing
}
STATUSES = {
    "unverified",  # not looked at yet
    "in-progress",
    "supported",  # evidence reproduces the claim as worded
    "partially-supported",  # true with a caveat; the slide or notes should carry it
    "contradicted",  # evidence disagrees; the slide must change
    "revise-slide",  # wording change agreed, not yet made in the deck
    "not-applicable",  # opinion, transition, or demo with nothing to check
    "superseded",  # no longer on the slide (deck revised); kept for the record and its evidence
}
PRIORITIES = {"high", "medium", "low"}
# A verdict needs something on disk a reader can rerun or open.
NEEDS_EVIDENCE = {"supported", "partially-supported", "contradicted"}
STATUS_ICON = {
    "unverified": "⬜",
    "in-progress": "🟨",
    "supported": "✅",
    "partially-supported": "🟧",
    "contradicted": "❌",
    "revise-slide": "✏️",
    "not-applicable": "➖",
    "superseded": "🗄️",
}


def load_all() -> list[tuple[Path, dict]]:
    return [(p, yaml.safe_load(p.read_text(encoding="utf-8")) or {}) for p in sorted(SLIDES_DIR.glob("*/claims.yaml"))]


def validate(entries: list[tuple[Path, dict]]) -> list[str]:
    errors = []
    for path, doc in entries:
        where = path.relative_to(ROOT)
        for key, typ in (("slide", int), ("title", str), ("section", str), ("claims", list)):
            if not isinstance(doc.get(key), typ):
                errors.append(f"{where}: '{key}' must be {typ.__name__}")
        if isinstance(doc.get("slide"), int) and not path.parent.name.startswith(f"{doc['slide']:02d}-"):
            errors.append(f"{where}: slide number {doc['slide']} does not match folder name")
        seen = set()
        for i, claim in enumerate(doc.get("claims") or []):
            cid = claim.get("id", f"#{i}")
            if cid in seen:
                errors.append(f"{where}: duplicate claim id {cid}")
            seen.add(cid)
            if not claim.get("text"):
                errors.append(f"{where}: {cid} has no text")
            if claim.get("status") == "revise-slide" and not claim.get("proposed_text"):
                errors.append(f"{where}: {cid} is 'revise-slide' but has no proposed_text")
            for key, allowed in (("kind", KINDS), ("status", STATUSES), ("priority", PRIORITIES)):
                if claim.get(key) not in allowed:
                    errors.append(f"{where}: {cid} {key}={claim.get(key)!r} not in {sorted(allowed)}")
            evidence = claim.get("evidence") or []
            if claim.get("status") in NEEDS_EVIDENCE and not evidence:
                errors.append(f"{where}: {cid} is '{claim['status']}' but lists no evidence")
            for ev in evidence:
                if not (path.parent / ev).exists():
                    errors.append(f"{where}: {cid} evidence path does not exist: {ev}")
    return errors


def render(entries: list[tuple[Path, dict]]) -> str:
    claims = [(p, d, c) for p, d in entries for c in d.get("claims") or []]
    counts = Counter(c["status"] for _, _, c in claims)
    lines = [
        "# Claims register",
        "",
        "Generated by `python tools/claims.py index` from `slides/*/claims.yaml`. Do not edit by hand.",
        "",
        "| Status | Count |",
        "|---|---:|",
        *[f"| {STATUS_ICON[s]} {s} | {counts[s]} |" for s in STATUS_ICON if counts[s]],
        f"| **total** | **{len(claims)}** |",
        "",
        "| Slide | Claim | Kind | Priority | Status |",
        "|---|---|---|---|---|",
    ]
    for path, doc, c in claims:
        folder = path.parent.relative_to(ROOT).as_posix()
        text = " ".join(str(c["text"]).split()).replace("|", "\\|")
        if len(text) > 110:
            text = text[:107] + "…"
        lines.append(
            f"| [{doc['slide']:02d} · {doc['title']}]({folder}/) | `{c['id']}` {text} "
            f"| {c['kind']} | {c['priority']} | {STATUS_ICON[c['status']]} {c['status']} |"
        )
    edits = [(p, d, c) for p, d, c in claims if c.get("proposed_text") and c["status"] != "superseded"]
    if edits:
        lines += [
            "",
            "## Pending deck edits",
            "",
            "**Agreed** = wording chosen, not yet in `talk/deck.html` (status `revise-slide`). **Suggested** = awaiting a decision.",
            "",
            "| Slide | Claim | | New wording |",
            "|---|---|---|---|",
        ]
        for path, doc, c in edits:
            folder = path.parent.relative_to(ROOT).as_posix()
            state = "Agreed" if c["status"] == "revise-slide" else "Suggested"
            new = " ".join(str(c["proposed_text"]).split()).replace("|", "\\|")
            lines.append(f"| [{doc['slide']:02d}]({folder}/) | `{c['id']}` | {state} | {new} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["validate", "index", "check"])
    args = parser.parse_args(argv)
    entries = load_all()
    errors = validate(entries)
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    if errors:
        return 1
    rendered = render(entries)
    if args.command == "index":
        REGISTER.write_text(rendered, encoding="utf-8")
        print(f"wrote {REGISTER.relative_to(ROOT)}")
    elif args.command == "check" and (not REGISTER.exists() or REGISTER.read_text(encoding="utf-8") != rendered):
        print("error: CLAIMS.md is stale; run `python tools/claims.py index`", file=sys.stderr)
        return 1
    print(f"ok: {sum(len(d.get('claims') or []) for _, d in entries)} claims in {len(entries)} slides")
    return 0


if __name__ == "__main__":
    sys.exit(main())
