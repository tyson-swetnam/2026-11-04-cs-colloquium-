"""Extract slide text and speaker notes from the exported deck.

    python tools/deck.py extract    # rewrite talk/slides.md from talk/deck.html
    python tools/deck.py scaffold   # create slides/NN-slug/ for any slide without a folder

The deck HTML is the source of truth for wording. Re-run `extract` after every
re-export so the diff of talk/slides.md shows exactly what changed on stage.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from bs4 import BeautifulSoup

ROOT = Path(__file__).resolve().parents[1]
DECK = ROOT / "talk" / "deck.html"
SLIDES_MD = ROOT / "talk" / "slides.md"
SLIDES_DIR = ROOT / "slides"


@dataclass
class Slide:
    number: int
    label: str
    text: list[str]
    notes: str


def read_deck(path: Path = DECK) -> list[Slide]:
    soup = BeautifulSoup(path.read_text(encoding="utf-8"), "html.parser")
    for tag in soup(["script", "style"]):
        tag.decompose()
    slides = []
    for section in soup.select("section.deck-slide"):
        lines = [ln.strip() for ln in section.get_text("\n").splitlines()]
        slides.append(
            Slide(
                number=int(section["id"]),
                label=section.get("data-label", "").strip(),
                text=[ln for ln in lines if ln],
                notes=section.get("data-speaker-notes", "").strip(),
            )
        )
    return sorted(slides, key=lambda s: s.number)


def slide_folder(number: int) -> Path | None:
    matches = sorted(SLIDES_DIR.glob(f"{number:02d}-*"))
    return matches[0] if matches else None


def slugify(label: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-")
    return slug[:48].rstrip("-") or "untitled"


def extract(slides: list[Slide]) -> None:
    out = [
        "# Slide text and speaker notes",
        "",
        "Generated by `python tools/deck.py extract` from `talk/deck.html`. Do not edit by hand.",
        "",
    ]
    for s in slides:
        folder = slide_folder(s.number)
        link = f" · [evidence]({os.path.relpath(folder, SLIDES_MD.parent)}/)" if folder else ""
        out += [f'<a id="slide-{s.number:02d}"></a>', "", f"## {s.number:02d} · {s.label}{link}", ""]
        out += ["```text", *s.text, "```", ""]
        if s.notes:
            out += [f"> **Notes:** {s.notes}", ""]
    SLIDES_MD.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {SLIDES_MD.relative_to(ROOT)} ({len(slides)} slides)")


def scaffold(slides: list[Slide]) -> None:
    for s in slides:
        if slide_folder(s.number):
            continue
        folder = SLIDES_DIR / f"{s.number:02d}-{slugify(s.label)}"
        folder.mkdir(parents=True)
        (folder / "README.md").write_text(
            f"# Slide {s.number:02d} · {s.label}\n\nSee `claims.yaml` for the claims on this slide.\n",
            encoding="utf-8",
        )
        (folder / "claims.yaml").write_text(
            f"slide: {s.number}\ntitle: {s.label!r}\nsection: TODO\nclaims: []\n",
            encoding="utf-8",
        )
        print(f"created {folder.relative_to(ROOT)}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["extract", "scaffold"])
    args = parser.parse_args(argv)
    slides = read_deck()
    {"extract": extract, "scaffold": scaffold}[args.command](slides)
    return 0


if __name__ == "__main__":
    sys.exit(main())
